"use client";
import { useEffect, useState } from "react";

interface Stage { key: string; label: string; n: number; p50: number | null; p95: number | null; p99: number | null; min: number | null; max: number | null }
interface Summary {
  source: string; hours: number; turns: number; outcomes: Record<string, number>;
  errorRate: number | null; timeoutRate: number | null; retrievalCacheHitRate: number | null; speculativeHitRate: number | null; costPerTurnUsd: number | null;
  feedback: Record<string, number>;
  stages: { warm: Stage[]; cold: Stage[]; voice: Stage[]; text: Stage[] };
  caches: { name: string; size: number; hits: number; misses: number; hitRate: number | null }[];
  providers: Record<string, string>[];
  recent: Record<string, string | number | boolean | null>[];
}

const SOURCES: Record<string, string> = { live: "Live traffic", benchmark: "Benchmark runs (real providers, scripted audio)", "synthetic-load": "SYNTHETIC load test (mock providers)" };

export function MetricsDashboard() {
  const [source, setSource] = useState("live");
  const [hours, setHours] = useState(24);
  const [view, setView] = useState<"warm" | "cold" | "voice" | "text">("warm");
  const [data, setData] = useState<Summary | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    let alive = true;
    const load = () =>
      fetch(`/api/admin/metrics?source=${source}&hours=${hours}`)
        .then(async (r) => {
          if (!r.ok) throw new Error(((await r.json().catch(() => ({}))) as { error?: { message?: string } }).error?.message ?? `Server returned ${r.status}.`);
          return (await r.json()) as Summary;
        })
        .then((d) => {
          if (!alive) return;
          setData(d);
          setError(null);
        })
        .catch((e) => alive && setError(e instanceof Error && e.message !== "Failed to fetch" ? e.message : "Can't reach the server. Retrying…"));
    void load();
    const id = setInterval(load, 10_000);
    return () => { alive = false; clearInterval(id); };
  }, [source, hours]);

  const pct = (x: number | null) => (x === null ? "—" : `${(x * 100).toFixed(1)}%`);
  const ms = (x: number | null) => (x === null ? "—" : `${x}`);

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-end gap-3">
        <div className="flex-1">
          <p className="eyebrow mb-2">Administration</p>
          <h1 className="font-display text-2xl font-semibold text-white">Performance</h1>
          <p className="text-sm text-faint">Recorded turn measurements only. Percentiles are nearest-rank; with fewer than 100 samples p99 equals the maximum.</p>
        </div>
        <select aria-label="Data source" className="input !w-auto" value={source} onChange={(e) => setSource(e.target.value)}>
          {Object.entries(SOURCES).map(([k, v]) => <option key={k} value={k}>{v}</option>)}
        </select>
        <select aria-label="Time window" className="input !w-auto" value={hours} onChange={(e) => setHours(Number(e.target.value))}>
          {[1, 24, 168, 720].map((h) => <option key={h} value={h}>Last {h < 24 ? `${h} h` : `${h / 24} d`}</option>)}
        </select>
      </div>
      {source === "synthetic-load" && <div className="rounded-xl border border-amber-400/25 bg-amber-400/10 p-3 text-sm text-amber-200">Synthetic data: generated by the load-test harness with mock providers. It measures orchestration overhead and concurrency behaviour, not real model latency.</div>}
      {error && <div role="alert" className="rounded-xl border border-rose-500/30 bg-rose-500/10 p-3 text-sm text-rose-300">Couldn&apos;t load metrics: {error}</div>}
      {!data ? (!error && <p className="text-sm text-faint">Loading…</p>) : (
        <>
          <div className="grid gap-3 sm:grid-cols-3 lg:grid-cols-6">
            {[
              ["Turns", String(data.turns)],
              ["Errors", pct(data.errorRate)],
              ["Timeouts", pct(data.timeoutRate)],
              ["Retrieval cache hits", pct(data.retrievalCacheHitRate)],
              ["Pre-rendered turns", pct(data.speculativeHitRate)],
              ["Cost / turn", data.costPerTurnUsd === null ? "n/a" : `$${data.costPerTurnUsd.toFixed(5)}`],
            ].map(([k, v]) => (
              <div key={k} className="glass rounded-xl p-3">
                <div className="text-xs text-faint">{k}</div>
                <div className="font-display tabular mt-1 text-2xl font-semibold text-white">{v}</div>
              </div>
            ))}
          </div>
          <div className="text-xs text-faint">Outcomes: {Object.entries(data.outcomes).map(([k, v]) => `${k} ${v}`).join(" · ")} · Feedback: 👍 {data.feedback.up ?? 0} 👎 {data.feedback.down ?? 0}</div>

          <section className="overflow-x-auto glass rounded-2xl">
            <div className="flex gap-2 border-b hairline p-3 text-sm">
              {(["warm", "cold", "voice", "text"] as const).map((v) => (
                <button key={v} type="button" aria-pressed={view === v} onClick={() => setView(v)} className={`rounded-lg px-3 py-1.5 text-[13px] transition ${view === v ? "bg-violet-500/20 text-white ring-1 ring-violet-400/40" : "text-white/60 hover:bg-white/5"}`}>{v === "warm" ? "Warm (all)" : v === "cold" ? "Cold start" : v === "voice" ? "Voice (warm)" : "Text (warm)"}</button>
              ))}
            </div>
            <table className="w-full text-sm">
              <thead className="bg-white/[0.03] text-left text-[11px] uppercase tracking-wider text-faint">
                <tr><th className="p-3">Stage (ms)</th><th className="p-3 text-right">n</th><th className="p-3 text-right">p50</th><th className="p-3 text-right">p95</th><th className="p-3 text-right">p99</th><th className="p-3 text-right">max</th></tr>
              </thead>
              <tbody>
                {data.stages[view].map((s) => (
                  <tr key={s.key} className="border-t hairline">
                    <td className="p-3">{s.label}</td>
                    <td className="tabular p-3 text-right">{s.n}</td>
                    <td className="tabular p-3 text-right">{ms(s.p50)}</td>
                    <td className="tabular p-3 text-right">{ms(s.p95)}</td>
                    <td className="tabular p-3 text-right">{ms(s.p99)}</td>
                    <td className="tabular p-3 text-right">{ms(s.max)}</td>
                  </tr>
                ))}
                {!data.stages[view].length && <tr><td className="p-6 text-center text-faint" colSpan={6}>No turns recorded in this window.</td></tr>}
              </tbody>
            </table>
          </section>

          <section className="glass rounded-2xl p-4 text-xs text-white/65">
            <div className="eyebrow mb-2">Providers in this window</div>
            {data.providers.map((p, i) => <div key={i}>{Object.entries(p).map(([k, v]) => `${k}: ${v}`).join(" · ")}</div>)}
            <div className="eyebrow mb-2 mt-4">In-process caches (since last restart)</div>
            {data.caches.map((c) => <div key={c.name}>{c.name}: {c.size} entries · {c.hits} hits / {c.misses} misses · hit rate {pct(c.hitRate)}</div>)}
          </section>

          <section className="overflow-x-auto glass rounded-2xl">
            <table className="w-full text-xs">
              <thead className="bg-white/[0.03] text-left uppercase tracking-wider text-faint">
                <tr>{["at", "mode", "outcome", "perceived", "EOS→audio", "STT", "search", "TTFT", "TTS", "total", "spec", "cache"].map((h) => <th key={h} className="p-2">{h}</th>)}</tr>
              </thead>
              <tbody>
                {data.recent.map((r) => (
                  <tr key={String(r.turnId)} className="tabular border-t hairline">
                    <td className="p-2">{new Date(String(r.at)).toLocaleTimeString()}{r.coldStart ? " (cold)" : ""}</td>
                    <td className="p-2">{String(r.mode)}</td>
                    <td className="p-2">{String(r.outcome)}</td>
                    {["clientEosToFirstAudioMs", "eosToFirstAudioMs", "sttMs", "retrievalMs", "llmTtftMs", "ttsFirstChunkMs", "totalMs"].map((k) => <td key={k} className="p-2">{r[k] ?? "—"}</td>)}
                    <td className="p-2">{r.speculativeHit === null ? "—" : r.speculativeHit ? "yes" : "no"}</td>
                    <td className="p-2">{r.retrievalCacheHit === null ? "—" : r.retrievalCacheHit ? "yes" : "no"}</td>
                  </tr>
                ))}
                {!data.recent.length && <tr><td className="p-6 text-center text-faint" colSpan={12}>No recent turns.</td></tr>}
              </tbody>
            </table>
          </section>
        </>
      )}
    </div>
  );
}
